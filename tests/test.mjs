import { initializeTestEnvironment, assertSucceeds, assertFails } from "@firebase/rules-unit-testing";
import { readFileSync } from "node:fs";
import { doc, setDoc, getDoc, updateDoc, serverTimestamp } from "firebase/firestore";
const env = await initializeTestEnvironment({ projectId: "demo-jsph", firestore: { rules: readFileSync("firestore.rules", "utf8"), host: "127.0.0.1", port: 8085 } });
const T = "Abc123Abc123Abc123Abc123Abc123Ab";
const base = { role: "jobseeker", fullName: "Ana Reyes", phone: "09171234567", city: "Bacolod City", consent: true, jobCategories: ["Cook"] };
const ana = env.authenticatedContext("ana").firestore();
const anon = env.unauthenticatedContext().firestore();
let ok = 0, bad = 0;
const t = async (name, p) => { try { await p; ok++; console.log("PASS", name); } catch (e) { bad++; console.log("FAIL", name, e.message); } };
await t("old-style profile still saves", assertSucceeds(setDoc(doc(ana, "users/ana"), base)));
await t("alerts on, city, good token", assertSucceeds(setDoc(doc(ana, "users/ana"), { ...base, alerts: true, alertsScope: "city", alertsToken: T })));
await t("scope all", assertSucceeds(setDoc(doc(ana, "users/ana"), { ...base, alerts: true, alertsScope: "all", alertsToken: T })));
await t("short token rejected", assertFails(setDoc(doc(ana, "users/ana"), { ...base, alerts: true, alertsToken: T.slice(1) })));
await t("symbol token rejected", assertFails(setDoc(doc(ana, "users/ana"), { ...base, alerts: true, alertsToken: T.slice(1) + "-" })));
await t("bad scope rejected", assertFails(setDoc(doc(ana, "users/ana"), { ...base, alertsScope: "world" })));
await t("alerts must be bool", assertFails(setDoc(doc(ana, "users/ana"), { ...base, alerts: "yes" })));
await t("owner turns alerts off (unsubscribe while signed in)", assertSucceeds(updateDoc(doc(ana, "users/ana"), { alerts: false, updatedAt: serverTimestamp() })));
await t("signed-out unsubscribe click", assertSucceeds(setDoc(doc(anon, `unsubscribes/${T}`), { at: serverTimestamp() })));
await t("clicking twice works", assertSucceeds(setDoc(doc(anon, `unsubscribes/${T}`), { at: serverTimestamp() })));
await t("unsub extra field rejected", assertFails(setDoc(doc(anon, `unsubscribes/${T}`), { at: serverTimestamp(), uid: "x" })));
await t("unsub bad id rejected", assertFails(setDoc(doc(anon, "unsubscribes/hello"), { at: serverTimestamp() })));
await t("unsub client time rejected", assertFails(setDoc(doc(anon, `unsubscribes/${T}`), { at: new Date(0) })));
await t("unsub not readable", assertFails(getDoc(doc(anon, `unsubscribes/${T}`))));
await t("alertState not readable by user", assertFails(getDoc(doc(ana, "alertState/ana"))));
await t("alertState not writable by user", assertFails(setDoc(doc(ana, "alertState/ana"), { lastSentAt: 0 })));
await t("other user can't read profile token", assertFails(getDoc(doc(env.authenticatedContext("bob").firestore(), "users/ana"))));
console.log(`\n${ok} passed, ${bad} failed`);
await env.cleanup(); process.exit(bad ? 1 : 0);
